"""Subset Fluent System Icons (Regular + Filled) to the site's icons and write css/fluent-icons.css.

Run fluent_map.py first. Both scripts read fluent_src/ (not committed): FluentSystemIcons-{Regular,Filled}.ttf
and .json plus LICENSE from https://github.com/microsoft/fluentui-system-icons (fonts/ folder). Needs fontTools.
To add an icon: put its Font Awesome name and Fluent candidates in CANDS (fluent_map.py), then rerun both.
"""
import json
import sys
from pathlib import Path

from fontTools import subset

sys.stdout.reconfigure(encoding="utf-8")
HERE = Path(__file__).resolve().parent
SRC = HERE / "fluent_src"
SITE = HERE.parents[1]                                   # the Profile repo root
FONT_DIR = SITE / "assets" / "fonts" / "fluent-icons"
FONT_DIR.mkdir(parents=True, exist_ok=True)
MAP = json.loads((HERE / "fluent_map.json").read_text(encoding="utf-8"))

def build(style, key):
    codes = sorted({v[key] for v in MAP.values()})
    opts = subset.Options()
    opts.flavor = "woff"
    opts.layout_features = []
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    font = subset.load_font(str(SRC / f"FluentSystemIcons-{style}.ttf"), opts)
    s = subset.Subsetter(opts)
    s.populate(unicodes=codes)
    s.subset(font)
    out = FONT_DIR / f"fluent-icons-{style.lower()}.woff"
    subset.save_font(font, str(out), opts)
    print(f"{out.name}: {len(codes)} glyphs, {out.stat().st_size / 1024:.1f} KB")

build("Regular", "reg")
build("Filled", "fil")
lic = (SRC / "LICENSE").read_text(encoding="utf-8")
(FONT_DIR / "LICENSE.txt").write_text(
    "Fluent UI System Icons (https://github.com/microsoft/fluentui-system-icons)\n"
    "Subset to the icons used on this site; glyphs unchanged.\n\n" + lic, encoding="utf-8", newline="\n")

TILES = ".stat-icon-badge, .sim-icon-badge"     # solid blue tiles use the Filled style
classes = sorted(MAP)
sel = ",\n".join(f".theme-fluent .fa-{c}" for c in classes)
css = [
    "/* Fluent System Icons (MIT, (c) Microsoft; see assets/fonts/fluent-icons/LICENSE.txt).",
    "   GENERATED by scripts/fluent-icons/fluent_build.py: replaces the Font Awesome glyphs the site uses with the matching",
    "   Fluent icon. Brand logos and the tooth icons have no Fluent equivalent and stay Font Awesome.",
    "   Regular style everywhere; Filled style inside the solid blue icon tiles. */",
    "@font-face { font-family: \"Fluent Icons R\"; src: url(\"../assets/fonts/fluent-icons/fluent-icons-regular.woff?v=1\") format(\"woff\"); font-weight: normal; font-style: normal; font-display: block; }",
    "@font-face { font-family: \"Fluent Icons F\"; src: url(\"../assets/fonts/fluent-icons/fluent-icons-filled.woff?v=1\") format(\"woff\"); font-weight: normal; font-style: normal; font-display: block; }",
    "",
    sel + " {",
    "    font-family: \"Fluent Icons R\" !important;",
    "    font-weight: 400 !important;",
    "    font-style: normal !important;",
    "    font-size: 1.18em;",
    "    line-height: 1;",
    "    vertical-align: -0.2em;",
    "    -webkit-font-smoothing: antialiased;",
    "    -moz-osx-font-smoothing: grayscale;",
    "}",
]
for c in classes:
    css.append(f".theme-fluent .fa-{c}::before {{ content: \"\\{MAP[c]['reg']:x}\" !important; }}")
css.append("")
css.append(",\n".join(f".theme-fluent :is({TILES}) .fa-{c}" for c in classes) + " { font-family: \"Fluent Icons F\" !important; }")
for c in classes:
    css.append(f".theme-fluent :is({TILES}) .fa-{c}::before {{ content: \"\\{MAP[c]['fil']:x}\" !important; }}")
(SITE / "css" / "fluent-icons.css").write_text("\n".join(css) + "\n", encoding="utf-8", newline="\n")
print("css/fluent-icons.css written,", len(classes), "icons")
